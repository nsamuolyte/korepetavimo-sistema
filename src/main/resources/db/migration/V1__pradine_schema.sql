-- V1: pradinė korepetavimo sistemos schema (1 ir 2 sprintai).
-- Enum reikšmėms CHECK apribojimai sąmoningai nekuriami.
-- IF NOT EXISTS: esamose DB sukuriamos tik trūkstamos lentelės.

CREATE TABLE IF NOT EXISTS users (
                                     id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     first_name    VARCHAR(255) NOT NULL,
    last_name     VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    phone_number  VARCHAR(255),
    role          VARCHAR(255) NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE
    );

CREATE TABLE IF NOT EXISTS tutor_profiles (
                                              id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              user_id          BIGINT         NOT NULL UNIQUE REFERENCES users (id),
    subject          VARCHAR(255)   NOT NULL,
    education_level  VARCHAR(255)   NOT NULL,
    hourly_rate      NUMERIC(10, 2) NOT NULL,
    description      VARCHAR(2000),
    experience_years INTEGER        NOT NULL DEFAULT 0,
    approved         BOOLEAN        NOT NULL DEFAULT FALSE,
    rejected         BOOLEAN        NOT NULL DEFAULT FALSE
    );

CREATE TABLE IF NOT EXISTS tutor_subjects (
                                              tutor_profile_id BIGINT       NOT NULL REFERENCES tutor_profiles (id) ON DELETE CASCADE,
    subject          VARCHAR(100) NOT NULL,
    PRIMARY KEY (tutor_profile_id, subject)
    );

CREATE TABLE IF NOT EXISTS guardian_students (
                                                 id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                 guardian_id BIGINT       NOT NULL REFERENCES users (id),
    student_id  BIGINT       NOT NULL REFERENCES users (id),
    status      VARCHAR(255) NOT NULL,
    CONSTRAINT uk_guardian_students_guardian_student UNIQUE (guardian_id, student_id)
    );

CREATE TABLE IF NOT EXISTS availabilities (
                                              id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              tutor_id    BIGINT       NOT NULL REFERENCES users (id),
    day_of_week VARCHAR(255) NOT NULL,
    start_time  TIME(6)      NOT NULL,
    end_time    TIME(6)      NOT NULL,
    CONSTRAINT ck_availabilities_interval CHECK (start_time < end_time)
    );

CREATE TABLE IF NOT EXISTS lesson_packages (
                                               id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               tutor_id     BIGINT         NOT NULL REFERENCES users (id),
    name         VARCHAR(255)   NOT NULL,
    lesson_count INTEGER        NOT NULL,
    price        NUMERIC(10, 2) NOT NULL,
    active       BOOLEAN        NOT NULL DEFAULT TRUE
    );

CREATE TABLE IF NOT EXISTS package_purchases (
                                                 id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                 buyer_id          BIGINT       NOT NULL REFERENCES users (id),
    student_id        BIGINT       NOT NULL REFERENCES users (id),
    lesson_package_id BIGINT       NOT NULL REFERENCES lesson_packages (id),
    remaining_lessons INTEGER      NOT NULL,
    active            BOOLEAN      NOT NULL DEFAULT FALSE,
    purchased_at      TIMESTAMP(6) NOT NULL
    );

CREATE TABLE IF NOT EXISTS payments (
                                        id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        payer_id            BIGINT         NOT NULL REFERENCES users (id),
    package_purchase_id BIGINT         NOT NULL REFERENCES package_purchases (id),
    amount              NUMERIC(10, 2) NOT NULL,
    status              VARCHAR(255)   NOT NULL,
    external_id         VARCHAR(255),
    created_at          TIMESTAMP(6)   NOT NULL
    );

CREATE TABLE IF NOT EXISTS lessons (
                                       id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       tutor_id            BIGINT         NOT NULL REFERENCES users (id),
    student_id          BIGINT         NOT NULL REFERENCES users (id),
    booked_by_id        BIGINT         NOT NULL REFERENCES users (id),
    package_purchase_id BIGINT REFERENCES package_purchases (id),
    subject             VARCHAR(255)   NOT NULL,
    start_time          TIMESTAMP(6)   NOT NULL,
    end_time            TIMESTAMP(6)   NOT NULL,
    status              VARCHAR(255)   NOT NULL,
    price               NUMERIC(10, 2) NOT NULL,
    created_at          TIMESTAMP(6)   NOT NULL,
    cancellation_reason VARCHAR(500),
    reminder_sent       BOOLEAN,
    CONSTRAINT ck_lessons_interval CHECK (start_time < end_time)
    );

CREATE TABLE IF NOT EXISTS reviews (
                                       id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       lesson_id  BIGINT       NOT NULL REFERENCES lessons (id),
    author_id  BIGINT       NOT NULL REFERENCES users (id),
    rating     INTEGER      NOT NULL,
    comment    VARCHAR(1000),
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_reviews_lesson_author UNIQUE (lesson_id, author_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 10)
    );

CREATE TABLE IF NOT EXISTS messages (
                                        id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        sender_id    BIGINT        NOT NULL REFERENCES users (id),
    recipient_id BIGINT        NOT NULL REFERENCES users (id),
    content      VARCHAR(2000) NOT NULL,
    sent_at      TIMESTAMP(6)  NOT NULL,
    is_read      BOOLEAN       NOT NULL DEFAULT FALSE
    );

CREATE TABLE IF NOT EXISTS notifications (
                                             id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             recipient_id BIGINT       NOT NULL REFERENCES users (id),
    type         VARCHAR(255) NOT NULL,
    text         VARCHAR(500) NOT NULL,
    link         VARCHAR(255),
    created_at   TIMESTAMP(6) NOT NULL,
    is_read      BOOLEAN      NOT NULL DEFAULT FALSE
    );

CREATE TABLE IF NOT EXISTS payouts (
                                       id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       tutor_id     BIGINT         NOT NULL REFERENCES users (id),
    amount       NUMERIC(10, 2) NOT NULL,
    status       VARCHAR(255)   NOT NULL,
    requested_at TIMESTAMP(6)   NOT NULL
    );

CREATE INDEX IF NOT EXISTS ix_lessons_tutor_start     ON lessons (tutor_id, start_time);
CREATE INDEX IF NOT EXISTS ix_lessons_student_start   ON lessons (student_id, start_time);
CREATE INDEX IF NOT EXISTS ix_availabilities_tutor    ON availabilities (tutor_id);
CREATE INDEX IF NOT EXISTS ix_notifications_recipient ON notifications (recipient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_messages_pair           ON messages (sender_id, recipient_id, sent_at);